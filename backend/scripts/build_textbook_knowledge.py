def chunk_text(text: str, size=700, overlap=100) -> list[dict]:
    chunks = []
    start = 0
    while start < len(text):
        end = min(start + size, len(text))
        chunks.append({
            "start": start,
            "end": end,
            "text": text[start:end]
        })
        if end == len(text):
            break
        start = end - overlap
    return chunks


