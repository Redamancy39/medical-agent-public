def chunk_text(text: str, size: int = 700, overlap: int = 100) -> list[dict]:
    chunks = []
    start = 0
    while start < len(text):
        end = start + size
        chunk = text[start:end]
        if len(chunk.strip()) > 30:
            chunks.append({
                "start": start,
                "end": min(end, len(text)),
                "text": chunk.strip()
            })
        if end >= len(text):
            break
        start = end - overlap
    return chunks


